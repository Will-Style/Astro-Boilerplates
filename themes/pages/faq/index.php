                                            <summary class="c-accordion__summary qa__summary" data-accordion-summary itemprop="name">
                                                制作時に撮影した写真や動画素材の「2次利用」は可能ですか？
                                            </summary>
                                            <div class="c-accordion__content qa__content" data-accordion-content itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                                                <div class="c-accordion__inner qa__inner" itemprop="text">
                                                    原則として可能ですが、素材の契約内容によって一部制限がある場合がございます。<br>
                                                    当社や外部パートナーが撮影したオリジナルの素材については、Webサイト以外（パンフレット、SNS、採用活動など）への展開も柔軟に対応しております。ただし、一部の有料ストックフォトなどによっては、使用期限や媒体の制限、または別途追加費用が発生するケースがございます。トラブルを防ぐため、撮影前に「どのような媒体で2次利用する予定か」をあらかじめスタッフへお聞かせいただけますと幸いです。
                                                </div>
                                            </div>
                                        </details>

                                        <details class="c-accordion__details qa__details" data-accordion-details itemprop="mainEntity" itemscope itemtype="https://schema.org/Question">
                                            <summary class="c-accordion__summary qa__summary" data-accordion-summary itemprop="name">
                                                デザインや企画の提案時、ABC案（複数案）は作っていただけるのですか？
                                            </summary>
                                            <div class="c-accordion__content qa__content" data-accordion-content itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                                                <div class="c-accordion__inner qa__inner" itemprop="text">
                                                    
                                                    <p>
                                                        基本的には、私たちが「これがベスト」と確信を持った1案に絞ってご提案させていただいております。<br>
                                                        たくさんの選択肢（ABC案）を出す形をとらない理由は、以下の2つだからです。
                                                    </p>
                                                    <dl class="my-30">
                                                        <dt>理由1：リソースを集中させ、クオリティを最大化するため</dt>
                                                        <dd class="mt-5">ご予算と制作期間の中でエネルギーを3つに分散させるよりも、徹底したヒアリングと分析から導き出した「最も成果が出る1案」にすべてのリソースを注ぎ込み、細部まで徹底的にブラッシュアップした状態でお見せする方が、結果として圧倒的に質の高いクリエイティブを提供できると考えています。</dd>
                                                        <dt class="mt-10">理由2：一貫した「ブランドのブレ」を防ぐため</dt>
                                                        <dd class="mt-5">数撃ちゃ当たるの思想で無理にABC案を作ると、コンセプトの弱い案や、御社の本質から外れた案が混ざってしまい、社内での意思決定を迷わせる原因になります。私たちは「迷わせる提案」ではなく、「課題を解決する提案」を重視しています。</dd>
                                                    </dl>

                                                    <p>
                                                        <small>※ただし、ロゴデザインやメインビジュアルの方向性において、ロジックとして2つの異なるアプローチが考えられる場合は、それぞれのメリット・デメリットを添えて2〜3案をご提示し、議論のベースにしていただくこともございます。</small>
                                                    </p>
                                                </div>
                                            </div>
                                        </details>
                                        
